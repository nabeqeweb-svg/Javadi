def clean(s: str) -> str:
    s = s.replace("\xa0", " ")
    s = re.sub(r"[ \t\n\r]+", " ", s)
    for a, b in FIXES:
        s = s.replace(a, b)
    s = s.replace("‌ ", "‌").replace(" ‌", "‌")
    s = re.sub(r" {2,}", " ", s)
    return s.strip(" -–—‌ ")


def parse_source() -> tuple[str, list[dict]]:
    raw = SRC.read_text(errors="replace")
    start = raw.find('<div class="tab-pane fade in active imgmw" id="ltab1">')
    end = raw.find('<div class="tab-pane fade" id="ltab2">')
    body = raw[start:end]
    text = re.sub(r"<br\s*/?>", " ", body, flags=re.I)
    text = re.sub(r"</p>", " ", text, flags=re.I)
    text = re.sub(r"<[^>]+>", " ", text)
    text = htmllib.unescape(text)
    text = clean(text)
    parts = re.split(r"ماده (\d+) -\s*", text)
    articles: list[dict] = []
    for i in range(1, len(parts), 2):
        n = int(parts[i])
        blob = parts[i + 1] if i + 1 < len(parts) else ""
        blob = re.sub(r"قانون فوق مشتمل.*$", "", blob)
        blob = clean(blob)
        notes = [clean(x) for x in re.findall(
            r"تبصره(?:\s*\d+)?\s*-.*?(?=(?:تبصره(?:\s*\d+)?\s*-)|$)", blob
        )]
        main_for_clauses = blob
        clauses = []
        for m in re.finditer(
            r"(?:(?<=\s)|(?<=^))(\d+)\s*-\s+",
            main_for_clauses,
        ):
            num = int(m.group(1))
            start = m.end()
            nxt = re.search(r"(?:(?<=\s)|(?<=^))(\d+)\s*-\s+|تبصره", main_for_clauses[start:])
            end = start + nxt.start() if nxt else len(main_for_clauses)
            body_c = clean(main_for_clauses[start:end])
            if len(body_c) > 8 and num <= 20:
                clauses.append({"n": num, "t": body_c})
        articles.append(
            {
                "n": n,
                "text": blob,
                "notes": notes,
                "clauses": clauses,
            }
        )
    articles.sort(key=lambda a: a["n"])
    return text, articles


