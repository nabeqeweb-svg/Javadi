def extract_deadlines(text: str) -> list[str]:
    out = []
    for m in re.finditer(
        r"(ظرف|مهلت|حداکثر(?: ظرف)?|تا|در مدت)\s+([۰-۹0-9]+|یک|دو|سه|پنج|ده|پانزده|بیست|سی|یک ماه|دو ماه)\s*(روز|ماه|سال|ساعت)?",
        text,
    ):
        frag = clean(m.group(0))
        if frag not in out:
            out.append(frag)
    return out[:4]


def extract_refs(text: str, self_n: int) -> list[int]:
    refs = []
    for m in re.finditer(r"ماده\s*\(?\s*(\d+)\s*\)?", text):
        v = int(m.group(1))
        if 1 <= v <= 529 and v != self_n and v not in refs:
            refs.append(v)
    return refs[:6]


def auto_title(art: dict) -> str:
    if art["n"] in TITLES:
        return TITLES[art["n"]]
    s = first_sentence(art["text"])
    s = re.sub(r"^(در|به|از)\s+", "", s)
    if len(s) > 42:
        s = s[:42].rsplit(" ", 1)[0] + "…"
    return s or f"ماده {fa(art['n'])}"


def pillars_of(art: dict) -> list[str]:
    pts: list[str] = []
    if art["clauses"]:
        for c in art["clauses"][:8]:
            t = c["t"]
            if len(t) > 140:
                t = t[:140].rsplit(" ", 1)[0] + "…"
            pts.append(f"بند {fa(c['n'])}: {t}")
    else:
        bits = re.split(r"(?<=[.؛])\s+", art["text"])
        for b in bits:
            b = clean(b)
            if len(b) > 28:
                pts.append(b if len(b) < 160 else b[:160] + "…")
            if len(pts) >= 5:
                break
    for n in art["notes"][:3]:
        pts.append("تبصره: " + (n if len(n) < 160 else n[:160] + "…"))
    dls = extract_deadlines(art["text"] + " " + " ".join(art["notes"]))
    for d in dls:
        pts.append("مهلت یا زمان: " + d)
    return pts[:8]


def related_of(art: dict) -> list[int]:
    n = art["n"]
    rel = extract_refs(art["text"] + " " + " ".join(art["notes"]), n)
    for v in (n - 1, n + 1, n - 2, n + 2):
        if 1 <= v <= 529 and v not in rel:
            rel.append(v)
    # chapter mates of high value
    return rel[:8]


